"""Run the causal structural replay on cached Forexite minute quotes.

The cache is generated by ``forexite_history.py``.  This runner never fills a
missing minute: an M15, H1, or H4 candle is offered to the strategy only when
every constituent source minute exists and was available by that bar close.
Forexite does not publish historical bid/ask or execution costs in this
archive, so the default output is explicitly a *gross quote replay*, not a
broker-fill result.
"""
from __future__ import annotations

import argparse
from datetime import date
import json
from pathlib import Path
import sys

import pandas as pd

# Direct ``python scripts/run_forexite_replay.py`` execution otherwise places
# only ``scripts/`` on sys.path, not the repository package root.
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from quant.sequential_replay import run_sequential_replay


TF_RULES = {'M15': '15min', 'H1': '1h', 'H4': '4h'}


def _read_minutes(cache_dir: Path, symbol: str, start: date, end: date) -> pd.DataFrame:
    parts = []
    for path in sorted((cache_dir / 'days').glob('*/*.csv.gz')):
        provider_day = date.fromisoformat(path.name[:10])
        if provider_day < start or provider_day > end:
            continue
        frame = pd.read_csv(path, usecols=['timestamp', 'available_at', 'symbol', 'open', 'high', 'low', 'close'])
        frame = frame[frame.symbol == symbol]
        if not frame.empty:
            parts.append(frame.drop(columns='symbol'))
    if not parts:
        raise ValueError(f'No cached {symbol} data in requested range')
    data = pd.concat(parts, ignore_index=True)
    data['timestamp'] = pd.to_datetime(data.timestamp, utc=True)
    data['available_at'] = pd.to_datetime(data.available_at, utc=True)
    data = data.set_index('timestamp').sort_index()
    if data.index.has_duplicates:
        raise ValueError(f'{symbol} cache has duplicate minute labels')
    return data


def _complete_bars(minutes: pd.DataFrame, rule: str) -> pd.DataFrame:
    """Aggregate only uninterrupted source minutes with causal availability."""
    grouped = minutes.resample(rule, label='left', closed='left')
    result = grouped.agg(
        open=('open', 'first'), high=('high', 'max'), low=('low', 'min'), close=('close', 'last'),
        minute_count=('close', 'count'), latest_available_at=('available_at', 'max'),
    )
    expected = int(pd.Timedelta(rule) / pd.Timedelta(minutes=1))
    complete_at = result.index + pd.Timedelta(rule)
    result = result[(result.minute_count == expected) & (result.latest_available_at <= complete_at)]
    return result[['open', 'high', 'low', 'close']]


def build_frames(cache_dir: Path, symbol: str, start: date, end: date):
    minutes = _read_minutes(cache_dir, symbol, start, end)
    return {name: _complete_bars(minutes, rule) for name, rule in TF_RULES.items()}


def coverage(frames):
    return {
        name: {
            'bars': len(frame),
            'first_open_utc': None if frame.empty else frame.index[0].isoformat(),
            'last_open_utc': None if frame.empty else frame.index[-1].isoformat(),
        }
        for name, frame in frames.items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache-dir', type=Path, required=True)
    parser.add_argument('--symbol', choices=('XAUUSD', 'US30', 'SPX500'), required=True)
    parser.add_argument('--start', type=date.fromisoformat, default=date(2006, 1, 1))
    parser.add_argument('--end', type=date.fromisoformat, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--spread', type=float, default=0.0,
                        help='Absolute spread assumption; default zero because source has no bid/ask history.')
    parser.add_argument('--slippage', type=float, default=0.0)
    parser.add_argument('--commission', type=float, default=0.0)
    parser.add_argument('--risk-pct', type=float, default=1.0)
    args = parser.parse_args()
    frames = build_frames(args.cache_dir, args.symbol, args.start, args.end)
    result = run_sequential_replay(
        frames, args.symbol, start=pd.Timestamp(args.start, tz='UTC'),
        end=pd.Timestamp(args.end, tz='UTC') + pd.Timedelta(days=1),
        spread=args.spread, slippage=args.slippage, commission=args.commission, risk_pct=args.risk_pct,
    )
    result['source'] = {
        'provider': 'Forexite public MetaStock archive',
        'data_kind': 'Historical market quotes; not the connected MT5 broker feed',
        'bar_label_assumption': 'Provider minute label treated as open; OHLC available after one minute',
        'execution_scope': 'Gross quote replay unless explicit assumptions are provided',
        'historical_bid_ask_available': False,
        'historical_commission_available': False,
        'coverage': coverage(frames),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding='utf-8')
    print(json.dumps({'output': str(args.output.resolve()), 'summary': result['summary'],
                      'coverage': result['source']['coverage']}, indent=2))


if __name__ == '__main__':
    main()
