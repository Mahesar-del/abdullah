class Signal(models.Model):
    """
    The main signal generated by the Unified Signal Engine.
    Final verdict: BUY / SELL / WAIT
    """
    DIRECTION_CHOICES = [
        ('BUY',  '🟢 BUY'),
        ('SELL', '🔴 SELL'),
        ('WAIT', '🟡 WAIT'),
    ]

    STRENGTH_CHOICES = [
        ('STRONG',   'Strong'),
        ('MODERATE', 'Moderate'),
        ('WEAK',     'Weak'),
    ]

    STATUS_CHOICES = [
        ('ACTIVE',      'Active'),
        ('HIT_TP',      'Take Profit Hit'),
        ('HIT_SL',      'Stop Loss Hit'),
        ('EXPIRED',     'Expired'),
        ('CANCELLED',   'Cancelled'),
        ('INVALIDATED', 'Invalidated'),
    ]

    MODE_CHOICES = [
        ('PAPER', 'Paper / Unvalidated'),
        ('LIVE',  'Live (validation gate passed)'),
    ]

    # ── Core Fields ──────────────────────────────────────────────────────────
    instrument       = models.ForeignKey(Instrument, on_delete=models.CASCADE, related_name='signals')
    timeframe        = models.CharField(max_length=5)
    direction        = models.CharField(max_length=5, choices=DIRECTION_CHOICES, db_index=True)
    strength         = models.CharField(max_length=10, choices=STRENGTH_CHOICES)
    status           = models.CharField(max_length=15, choices=STATUS_CHOICES, default='ACTIVE', db_index=True)

    # ── Price Levels ─────────────────────────────────────────────────────────
    entry_price      = models.DecimalField(max_digits=20, decimal_places=8)
    stop_loss        = models.DecimalField(max_digits=20, decimal_places=8)
    take_profit_1    = models.DecimalField(max_digits=20, decimal_places=8)
    take_profit_2    = models.DecimalField(max_digits=20, decimal_places=8, null=True, blank=True)
    take_profit_3    = models.DecimalField(max_digits=20, decimal_places=8, null=True, blank=True)
    risk_reward      = models.DecimalField(max_digits=5, decimal_places=2, help_text="R:R ratio e.g. 2.5")

    # ── Confidence & Scoring ─────────────────────────────────────────────────
    confidence_score = models.DecimalField(max_digits=5, decimal_places=2, help_text="0-100 overall confidence")
    technical_score  = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    smc_score        = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    price_action_score = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    macro_score      = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    news_score       = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    institutional_score = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    ai_ml_score      = models.DecimalField(max_digits=5, decimal_places=2, default=0)

    # ── Analysis Notes ───────────────────────────────────────────────────────
    analysis_summary = models.TextField(blank=True)
    warnings         = models.JSONField(default=list, blank=True, help_text="e.g. ['News event in 2h', 'Low volume']")

    # ── Timestamps ───────────────────────────────────────────────────────────
    generated_at     = models.DateTimeField(auto_now_add=True, db_index=True)
    valid_until      = models.DateTimeField(null=True, blank=True)
    closed_at        = models.DateTimeField(null=True, blank=True)

    # ── Risk / pipeline state (single source of truth for API + dashboard + alerts) ──
    intermarket_score      = models.DecimalField(max_digits=5, decimal_places=2, default=0)
    mode                   = models.CharField(max_length=10, choices=MODE_CHOICES, default='PAPER', db_index=True)
    is_trade_allowed       = models.BooleanField(default=False, db_index=True)
    risk_rejection_reasons = models.JSONField(default=list, blank=True)
    recommended_lots       = models.FloatField(default=0.0)
    data_quality_score     = models.FloatField(default=100.0)
    data_flags             = models.JSONField(default=dict, blank=True, help_text="Per-engine data status (OK/STALE/MISSING/PROXY)")
    engine_detail          = models.JSONField(default=dict, blank=True)

    # ── Version 2.0: Independent Confluence, Regime & Decision Classes ──
    DECISION_CLASSES = [
        ('STRONG',     'Strong (Eligible)'),
        ('MODERATE',   'Moderate (Risk Gate Eligible)'),
        ('WEAK',       'Weak (WAIT)'),
        ('CONFLICT',   'Conflict (WAIT)'),
        ('BLACKOUT',   'Blackout (WAIT)'),
        ('DATA_ERROR', 'Data Error (WAIT)'),
    ]
    decision_class     = models.CharField(max_length=20, choices=DECISION_CLASSES, default='STRONG', db_index=True)
    market_regime      = models.CharField(max_length=50, default='TRENDING', db_index=True)
    independent_groups = models.JSONField(default=dict, blank=True, help_text="Evidence groups: Structure, Price Action, Regime/Momentum, Macro, Flow, News, Intermarket, ML")

    # ── Lifecycle tracking ──
    highest_tp_hit         = models.PositiveSmallIntegerField(default=0, help_text="0..3")
    tp1_hit_at             = models.DateTimeField(null=True, blank=True)
    tp2_hit_at             = models.DateTimeField(null=True, blank=True)
    tp3_hit_at             = models.DateTimeField(null=True, blank=True)
    invalidation_reason    = models.CharField(max_length=300, blank=True)

    def __str__(self):
        return f"{self.direction} {self.instrument.symbol} @ {self.entry_price} [{self.confidence_score}%]"

    @property
    def pips_to_sl(self):
        if self.direction == 'BUY':
            return float(self.entry_price - self.stop_loss) / float(self.instrument.pip_value)
        return float(self.stop_loss - self.entry_price) / float(self.instrument.pip_value)

    class Meta:
        ordering = ['-generated_at']
        indexes = [
            models.Index(fields=['instrument', 'status', '-generated_at']),
            models.Index(fields=['direction', 'status']),
        ]


