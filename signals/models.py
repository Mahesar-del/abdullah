class ValidationResult(models.Model):
    """
    Persisted outcome of a multi-asset backtest / walk-forward validation run evaluated against
    settings.VALIDATION_CRITERIA. The newest passing, non-expired row opens the LIVE gate.
    """
    KIND_CHOICES = [('BACKTEST_WALK_FORWARD', 'Backtest + Walk-forward'), ('ML', 'ML model validation')]

    kind        = models.CharField(max_length=30, choices=KIND_CHOICES, default='BACKTEST_WALK_FORWARD', db_index=True)
    symbols     = models.JSONField(default=list)
    timeframes  = models.JSONField(default=list)
    metrics     = models.JSONField(default=dict, blank=True)
    criteria    = models.JSONField(default=dict, blank=True)
    checks      = models.JSONField(default=list, blank=True, help_text="[{name, required, actual, passed}]")
    passed      = models.BooleanField(default=False, db_index=True)
    limitations = models.JSONField(default=list, blank=True)
    created_at  = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"Validation {self.kind} {'PASSED' if self.passed else 'FAILED'} @ {self.created_at:%Y-%m-%d %H:%M}"
