    title              = models.CharField(max_length=300, db_index=True)
    country            = models.CharField(max_length=50, blank=True, db_index=True)
    currency           = models.CharField(max_length=10, db_index=True)
    category           = models.CharField(max_length=30, choices=CATEGORY_CHOICES, default='OTHER', db_index=True)
    impact             = models.CharField(max_length=10, choices=IMPACT_CHOICES, db_index=True)
    event_time         = models.DateTimeField(db_index=True)
    forecast           = models.CharField(max_length=50, blank=True)
    previous           = models.CharField(max_length=50, blank=True)
    actual             = models.CharField(max_length=50, blank=True)
    surprise_pct       = models.FloatField(null=True, blank=True, help_text="Percentage or standard dev surprise")
    market_reaction    = models.CharField(max_length=20, blank=True, help_text="BULLISH, BEARISH, NEUTRAL")
    blackout_mins_before = models.IntegerField(default=30)
    blackout_mins_after  = models.IntegerField(default=30)
    source             = models.CharField(max_length=100, blank=True)
    created_at         = models.DateTimeField(auto_now_add=True)

    # ── Event engine fields (Checklist §4) ──
    EVENT_TYPE_CHOICES = [
        ('NFP', 'Non-Farm Payrolls'), ('CPI', 'CPI'), ('PPI', 'PPI'), ('GDP', 'GDP'),
        ('PMI', 'PMI'), ('RETAIL_SALES', 'Retail Sales'), ('EMPLOYMENT', 'Employment / Unemployment / Wages'),
        ('RATE_DECISION', 'Interest Rate Decision'), ('CB_SPEECH', 'Central Bank Speech / Minutes'),
        ('OTHER', 'Other'),
    ]
    RELEASE_STATUS_CHOICES = [
        ('SCHEDULED', 'Scheduled'), ('RELEASED', 'Released'), ('REVISED', 'Revised'),
    ]
    event_type             = models.CharField(max_length=20, choices=EVENT_TYPE_CHOICES, default='OTHER', db_index=True)
    affected_instruments   = models.JSONField(default=list, blank=True)
    affected_asset_classes = models.JSONField(default=list, blank=True)
    release_status         = models.CharField(max_length=12, choices=RELEASE_STATUS_CHOICES, default='SCHEDULED', db_index=True)
    revision_note          = models.CharField(max_length=300, blank=True)
    previous_revised       = models.CharField(max_length=50, blank=True)
    actual_source          = models.CharField(max_length=100, blank=True)
    source_url             = models.CharField(max_length=500, blank=True)
    external_key           = models.CharField(max_length=64, null=True, blank=True, unique=True)
    fetched_at             = models.DateTimeField(null=True, blank=True, help_text="When this record was last confirmed against the source")

    @property
    def data_age_hours(self):
        from django.utils import timezone as dj_tz
        if not self.fetched_at:
            return None
        return round((dj_tz.now() - self.fetched_at).total_seconds() / 3600.0, 2)

    @property
    def data_freshness(self) -> str:
        age = self.data_age_hours
        if age is None:
            return 'UNKNOWN'
        return 'FRESH' if age <= 24 else 'STALE'

    def __str__(self):
        return f"[{self.impact}] {self.currency} - {self.title} @ {self.event_time}"

    @property
    def is_in_blackout(self) -> bool:
        """Check if current time is within this event's blackout window"""
        from django.utils import timezone as dj_tz
        from datetime import timedelta
        now = dj_tz.now()
        start = self.event_time - timedelta(minutes=self.blackout_mins_before)
        end = self.event_time + timedelta(minutes=self.blackout_mins_after)
        return start <= now <= end

    class Meta:
        ordering = ['event_time']
        indexes = [
            models.Index(fields=['currency', 'impact', 'event_time']),
            models.Index(fields=['category', 'event_time']),
        ]



