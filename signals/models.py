class NotificationPreference(models.Model):
    """
    Dashboard ON/OFF switches. One row per (channel, category).
    Missing rows mean ENABLED (default-on). category='ALL' switches off a whole channel.
    """
    CATEGORY_CHOICES = [('ALL', 'All categories')] + [c for c in AlertDelivery.CATEGORY_CHOICES if c[0] not in ('TEST', 'SYSTEM')]

    channel    = models.CharField(max_length=20, db_index=True)
    category   = models.CharField(max_length=20, choices=CATEGORY_CHOICES, default='ALL')
    enabled    = models.BooleanField(default=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        unique_together = [('channel', 'category')]

    def __str__(self):
        return f"{self.channel}/{self.category}: {'ON' if self.enabled else 'OFF'}"

    @classmethod
    def is_enabled(cls, channel: str, category: str) -> bool:
        rows = {(r.channel, r.category): r.enabled
                for r in cls.objects.filter(channel=channel, category__in=['ALL', category])}
        if rows.get((channel, 'ALL')) is False:
            return False
        return rows.get((channel, category), True)


